import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import type { Manifest } from '../manifest.js';
import { fromRepo } from '../paths.js';
import { takesOf } from './run.js';
import type { SfxSpec } from './spec.js';

const run = promisify(execFile);

export const SPRITE_DIR = 'apps/client/public/assets/audio';
export const SPRITE_TS = 'apps/client/src/audio/sfxSprite.ts';
/** Silence between clips so codec padding never bleeds into a neighbour. */
export const GAP_MS = 250;

export interface PickedTake {
  id: string;
  file: string;
  entryId: string;
  reviewed: boolean;
}

/** Per clip: the approved take, else the newest completed one (flagged as unreviewed). */
export function pickTakes(spec: SfxSpec, manifest: Manifest): PickedTake[] {
  return spec.clips.map((clip) => {
    const takes = takesOf(manifest, spec, clip);
    const approved = takes.find((e) => e.outputs.some((o) => o.review === 'approved'));
    const pick = approved ?? takes.at(-1);
    const out = pick?.outputs[0];
    if (!pick || !out) throw new Error(`clip ${clip.id} has no completed take`);
    return { id: clip.id, file: out.file, entryId: pick.id, reviewed: Boolean(approved) };
  });
}

/** Sprite offsets in ms: each clip starts after the previous one plus a gap. */
export function layoutSprite(durationsMs: number[], gapMs = GAP_MS): [number, number][] {
  let at = 0;
  return durationsMs.map((d) => {
    const slot: [number, number] = [at, d];
    at += d + gapMs;
    return slot;
  });
}

export function spriteModule(ids: string[], slots: [number, number][]): string {
  const rows = ids.map((id, i) => {
    const [start, dur] = slots[i] ?? [0, 0];
    return `  '${id}': [${String(start)}, ${String(dur)}],`;
  });
  return `// Generated by \`pnpm --filter @pixel-packs/artgen start sfx-sprite\`. Do not edit.
/** SFX audio sprite (GDD §20): [start ms, duration ms] in /assets/audio/sfx.{webm,mp3}. */
export const SFX_SPRITE = {
${rows.join('\n')}
} as const satisfies Record<string, readonly [number, number]>;

export type SfxId = keyof typeof SFX_SPRITE;
`;
}

async function durationMs(file: string): Promise<number> {
  const { stdout } = await run('ffprobe', [
    ...['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file],
  ]);
  return Math.round(Number(stdout.trim()) * 1000);
}

/**
 * Trims leading/trailing silence, fades the tail out over 40 ms (a fade-in on the
 * reversed clip) against clicks, then evens out loudness across the set.
 */
export const CLEAN_FILTER = [
  'silenceremove=start_periods=1:start_threshold=-55dB',
  'areverse',
  'silenceremove=start_periods=1:start_threshold=-55dB',
  'afade=t=in:d=0.04',
  'areverse',
  'loudnorm=I=-20:TP=-3:LRA=11',
].join(',');

export async function buildSprite(
  spec: SfxSpec,
  manifest: Manifest,
  log: (msg: string) => void,
): Promise<void> {
  const picks = pickTakes(spec, manifest);
  const tmp = await mkdtemp(join(tmpdir(), 'sfx-sprite-'));
  try {
    const parts: string[] = [];
    const durations: number[] = [];
    const gap = join(tmp, 'gap.wav');
    await run('ffmpeg', [
      ...['-y', '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=mono'],
      ...['-t', String(GAP_MS / 1000), '-c:a', 'pcm_s16le', gap],
    ]);
    for (const [i, p] of picks.entries()) {
      const out = join(tmp, `${String(i)}.wav`);
      await run('ffmpeg', [
        ...['-y', '-i', fromRepo(p.file), '-af', CLEAN_FILTER],
        ...['-ar', '44100', '-ac', '1', '-c:a', 'pcm_s16le', out],
      ]);
      durations.push(await durationMs(out));
      parts.push(out, gap);
      if (!p.reviewed) log(`  ${p.id}: using unreviewed ${p.entryId}`);
    }
    const list = join(tmp, 'list.txt');
    await writeFile(list, parts.map((f) => `file '${f}'`).join('\n'));
    const joined = join(tmp, 'sprite.wav');
    await run('ffmpeg', ['-y', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', joined]);
    await mkdir(fromRepo(SPRITE_DIR), { recursive: true });
    const webm = fromRepo(`${SPRITE_DIR}/sfx.webm`);
    const mp3 = fromRepo(`${SPRITE_DIR}/sfx.mp3`);
    await run('ffmpeg', ['-y', '-i', joined, '-c:a', 'libopus', '-b:a', '64k', webm]);
    await run('ffmpeg', ['-y', '-i', joined, '-c:a', 'libmp3lame', '-b:a', '96k', mp3]);
    const slots = layoutSprite(durations);
    await writeFile(
      fromRepo(SPRITE_TS),
      spriteModule(
        picks.map((p) => p.id),
        slots,
      ),
    );
    log(`wrote ${SPRITE_DIR}/sfx.{webm,mp3} and ${SPRITE_TS} (${String(picks.length)} clips)`);
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}
