import { readFile, writeFile } from 'node:fs/promises';
import { CARD_CATALOG } from '@pixel-packs/shared';
import { bbox } from '../compose/pixels.js';
import { decodePng } from '../png.js';
import { fromRepo } from '../paths.js';

export const ART_LAYOUT_PATH = 'packages/shared/src/data/cards/artLayout.ts';

/** Rows of transparent space below each card's sprite (its drop to the window's bottom row). */
export async function measureArtDrops(): Promise<Record<string, number>> {
  const drops: Record<string, number> = {};
  for (const c of CARD_CATALOG) {
    const png = decodePng(await readFile(fromRepo(`apps/client/public/assets/cards/${c.id}.png`)));
    const b = bbox(png);
    drops[c.id] = b ? png.height - 1 - b.y1 : 0;
  }
  return drops;
}

export function artLayoutSource(drops: Record<string, number>): string {
  const rows = Object.entries(drops)
    .map(([id, d]) => `  '${id}': ${String(d)},`)
    .join('\n');
  return `// Generated by \`pnpm --filter @pixel-packs/artgen start art-layout\`; do not edit by hand.

/**
 * Art pixels to move each card's art down so its sprite stands on the art
 * window's bottom row (GDD §4: art is bottom-aligned). Measured from the
 * final PNGs in \`apps/client/public/assets/cards/\`.
 */
export const CARD_ART_DROP: Readonly<Record<string, number>> = {
${rows}
};
`;
}

export async function writeArtLayout(): Promise<string> {
  await writeFile(fromRepo(ART_LAYOUT_PATH), artLayoutSource(await measureArtDrops()));
  return ART_LAYOUT_PATH;
}
